"""Evaluate the final IDSS once on the test set (December 2019).

Usage (from the repository root, after scripts/calibrate_parameters.py and
after copying the selected values into rentwise/config.py):

    uv run python scripts/evaluate_test.py

Writes  results/test_evaluation.md

The price models are fitted on the training set (before December 2019) with
the parameters of rentwise/config.py, and every test listing goes through the
same price assessment (A1) as the application. The recommendations are
produced for one simulated renter per test listing (scripts/_renters.py).
No parameter is chosen here.
"""

from __future__ import annotations

import numpy as np
import pandas as pd

from _common import RESULTS, TEST_FROM, load_periods, md_table, metrics, write
from _renters import simulate
from calibrate_parameters import REVIEW_MAX, classify, price_assessments, shares
from rentwise import config
from rentwise.price import RidgeKnnPriceAssessor

OUT = RESULTS / "test_evaluation.md"
POSITIONS = ["below", "in_line", "moderately_above", "significantly_above"]


def main() -> None:
    d = load_periods()
    train, test = d["train"], d["test"]
    assessor = RidgeKnnPriceAssessor(train)
    a1 = assessor.assess_frame(test)
    y, ref = test.price.to_numpy(), a1.reference.to_numpy()
    suff = a1.evidence_sufficient.to_numpy()
    full = (a1.n_comparables >= config.KNN_K).to_numpy()

    # --- Reference accuracy ----------------------------------------------------
    accuracy = [("All test listings", {"Listings": len(test), **metrics(y, ref)})]
    for lvl, label in (("city", "Comparables in the same city"),
                       ("state", "Comparables in the same state"),
                       ("none", "No comparables")):
        m = (a1.level == lvl).to_numpy()
        if m.any():
            accuracy.append((label, {"Listings": int(m.sum()), **metrics(y[m], ref[m])}))
    for m, label in ((suff, "Sufficient evidence"), (~suff, "Insufficient evidence")):
        accuracy.append((label, {"Listings": int(m.sum()), **metrics(y[m], ref[m])}))

    # --- Evidence --------------------------------------------------------------
    evidence = {
        "Sufficient": {"Share": float(suff.mean())},
        "Insufficient: fewer than k comparables": {"Share": float((~full).mean())},
        "Insufficient: too dissimilar (mean distance > d_max)": {"Share": float((full & ~suff).mean())},
    }

    # --- Price positions and drift ---------------------------------------------
    pos = a1.position[suff]
    position_rows = {p.replace("_", " ").capitalize(): {"Share": float((pos == p).mean())}
                     for p in POSITIONS}
    gap = a1.gap.to_numpy()
    drift = {"All test listings": {"Median signed gap": float(np.median(gap))},
             "Sufficient evidence": {"Median signed gap": float(np.median(gap[suff]))}}

    # --- Recommendations for simulated renters ---------------------------------
    pairs = simulate(test, reference=train)
    classes, rules = classify(pairs, price_assessments(a1))
    rec = shares(classes, rules)
    insufficient_reviews = float(np.mean((rules == "R3") & ~suff))

    out = [
        "# Evaluation of the final IDSS on the test set",
        "",
        "Generated by `scripts/evaluate_test.py`. Do not edit by hand.",
        "",
        f"- Training set: {len(train):,} listings posted before {TEST_FROM}",
        f"- Test set: {len(test):,} listings posted from {TEST_FROM} (December 2019), evaluated once",
        f"- Parameters (rentwise/config.py): Ridge alpha = {config.RIDGE_ALPHA:g}, k = {config.KNN_K}, "
        f"d_max = {config.MAX_MEAN_DISTANCE:.2f}, b1 = {config.IN_LINE_BAND:.2f}, "
        f"b2 = {config.MODERATE_BAND:.2f}, fit thresholds {config.FIT_VERY_LOW:.2f} / {config.FIT_GOOD:.2f}",
        "",
        "## 1. Accuracy of the reference asking rent (Ridge)",
        "",
        md_table(accuracy, first="Test listings"),
        "",
        "## 2. Evidence sufficiency",
        "",
        md_table(evidence, first="Outcome"),
        "",
        "## 3. Price positions (test listings with sufficient evidence)",
        "",
        md_table(position_rows, first="Position"),
        "",
        "Calibration target on the validation period: about 49% in line, 10% significantly above.",
        "",
        "## 4. Temporal drift",
        "",
        "Gap = (asking - reference) / reference. A positive median means the reference, built",
        "from older listings, under-estimates the asking rents of December 2019.",
        "",
        md_table(drift, first="Test listings"),
        "",
        "## 5. Recommendations for simulated renters",
        "",
        f"One simulated renter per test listing ({len(test):,} assessments, `scripts/_renters.py`).",
        "",
        md_table({"Test set": rec}, first="Assessments"),
        "",
        f"- Review share: {rec['Review']:.1%} (criterion: at most {REVIEW_MAX:.0%})",
        f"- Assessments sent to Review with insufficient price evidence: {insufficient_reviews:.1%}",
    ]
    write(OUT, out)


if __name__ == "__main__":
    main()
